router = APIRouter(
    prefix="/orders",
    tags=["Order"],
)

_DOMAIN_ERRORS = (
    OrderNotFoundError,
    OrderForbiddenError,
    InvalidOrderReferenceError,
    OrderConflictError,
)
_NOT_FOUND_DETAIL = "Order not found"
_CONFLICT_DETAIL = "Order conflicts with an existing order"
_UNAUTHORIZED_RESPONSE = {
    "description": "Invalid or expired authentication credentials"
}
_FORBIDDEN_RESPONSE = {"description": FORBIDDEN_DETAIL}
_NOT_FOUND_RESPONSE = {"description": _NOT_FOUND_DETAIL}
_UNKNOWN_REFERENCE_RESPONSE = {
    "description": "Validation error or unknown status, type, zone, organization or user"
}


def _to_http(exc: Exception) -> HTTPException:
    """Map a domain error to its HTTP response. Details are fixed texts or our own messages."""
    if isinstance(exc, OrderNotFoundError):
        return HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail=_NOT_FOUND_DETAIL
        )
    if isinstance(exc, OrderForbiddenError):
        return HTTPException(
            status_code=status.HTTP_403_FORBIDDEN, detail=FORBIDDEN_DETAIL
        )
    if isinstance(exc, OrderConflictError):
        return HTTPException(
            status_code=status.HTTP_409_CONFLICT, detail=_CONFLICT_DETAIL
        )
    return HTTPException(
        status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
        detail=str(exc),
    )


def _to_list_item(order: OrderDB, manager_id: uuid.UUID | None) -> OrderListItem:
    return OrderListItem(
        id=order.id,
        tracking_number=order.tracking_number,
        status=order.status,
        partner_id=order.partner_id,
        service_type=order.service_type,
        zone_id=order.zone_id,
        courier_id=order.courier_id,
        manager_id=manager_id,
        created_at=order.created_at,
        updated_at=order.updated_at,
        delivered_at=order.delivered_at,
    )


def _to_operation(detail: OrderDetail, user: UserRead) -> OperationRead | None:
    """Return the operation block; internal fields only for admins and the order's manager."""
    if detail.operation is None:
        return None
    operation = OperationRead.model_validate(detail.operation)
    if Order.is_privileged(detail, user):
        return operation
    return operation.model_copy(
        update={"carrier_id": None, "route_id": None, "internal_comment": None}
    )


def _to_read(detail: OrderDetail, user: UserRead) -> OrderRead:
    order = detail.order
    return OrderRead(
        id=order.id,
        tracking_number=order.tracking_number,
        external_order_id=order.external_order_id,
        partner_id=order.partner_id,
        service_type=order.service_type,
        zone_id=order.zone_id,
        courier_id=order.courier_id,
        status=order.status,
        tracking_url=order.tracking_url,
        created_at=order.created_at,
        updated_at=order.updated_at,
        delivered_at=order.delivered_at,
        sender=SenderRead.model_validate(detail.sender) if detail.sender else None,
        recipient=RecipientRead.model_validate(detail.recipient)
        if detail.recipient
        else None,
        parcel=ParcelRead.model_validate(detail.parcel) if detail.parcel else None,
        schedule=ScheduleRead.model_validate(detail.schedule)
        if detail.schedule
        else None,
        payment=PaymentRead.model_validate(detail.payment) if detail.payment else None,
        operation=_to_operation(detail, user),
        status_history=[
            StatusHistoryRead.model_validate(item) for item in detail.history
        ],
    )


@router.post(
    "",
    response_model=OrderRead,
    status_code=status.HTTP_201_CREATED,
    summary="Create an order",
    description=(
        "Create an order with its sender, recipient, parcel, schedule and payment blocks "
        "and the first status. The tracking number is generated by the server. Admins "
        "must send partner_id; other users create orders for their own organization."
    ),
    responses={
        status.HTTP_401_UNAUTHORIZED: _UNAUTHORIZED_RESPONSE,
        status.HTTP_403_FORBIDDEN: _FORBIDDEN_RESPONSE,
        status.HTTP_409_CONFLICT: {"description": _CONFLICT_DETAIL},
        status.HTTP_422_UNPROCESSABLE_CONTENT: _UNKNOWN_REFERENCE_RESPONSE,
    },
)
async def create_order(
    data: OrderCreate,
    current_user: UserRead = Depends(get_current_user),
    session: AsyncSession = Depends(get_session),
) -> OrderRead:
    try:
        detail = await Order(session).create(data, current_user)
    except _DOMAIN_ERRORS as exc:
        raise _to_http(exc) from exc
    return _to_read(detail, current_user)


@router.get(
    "",
    response_model=list[OrderListItem],
    status_code=status.HTTP_200_OK,
    summary="List orders visible to the user",
    description=(
        "Admins see every order. Other users see orders of their organization (as sender), "
        "orders they manage, deliver or receive. Returns the X-Total-Count header with the "
        "total number of matching orders."
    ),
    responses={status.HTTP_401_UNAUTHORIZED: _UNAUTHORIZED_RESPONSE},
)
async def list_orders(
    response: Response,
    limit: int = Query(default=50, ge=1, le=100),
    offset: int = Query(default=0, ge=0),
    order_status: int | None = Query(default=None, alias="status"),
    zone_id: uuid.UUID | None = None,
    partner_id: uuid.UUID | None = None,
    courier_id: uuid.UUID | None = None,
    manager_id: uuid.UUID | None = None,
    created_from: datetime | None = None,
    created_to: datetime | None = None,
    current_user: UserRead = Depends(get_current_user),
    session: AsyncSession = Depends(get_session),
) -> list[OrderListItem]:
    flt = OrderFilter(
        status=order_status,
        zone_id=zone_id,
        partner_id=partner_id,
        courier_id=courier_id,
        manager_id=manager_id,
        created_from=created_from,
        created_to=created_to,
    )
    rows, total = await Order(session).list(current_user, limit, offset, flt)
    response.headers["X-Total-Count"] = str(total)
    return [_to_list_item(row[0], row[1]) for row in rows]


