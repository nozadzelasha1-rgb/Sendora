@router.delete(
    "/{order_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Cancel an order",
    description=(
        "Soft-cancel the order: its status becomes cancelled and a history row is written. "
        "The data is kept. Requires a Bearer token of an admin role. Cancelling twice is allowed."
    ),
    responses={
        status.HTTP_401_UNAUTHORIZED: _UNAUTHORIZED_RESPONSE,
        status.HTTP_403_FORBIDDEN: _FORBIDDEN_RESPONSE,
        status.HTTP_404_NOT_FOUND: _NOT_FOUND_RESPONSE,
    },
)
async def cancel_order(
    order_id: int,
    current_user: UserRead = Depends(get_current_user),
    session: AsyncSession = Depends(get_session),
) -> Response:
    try:
        await Order(session).cancel(order_id, current_user)
    except _DOMAIN_ERRORS as exc:
        raise _to_http(exc) from exc
    return Response(status_code=status.HTTP_204_NO_CONTENT)
